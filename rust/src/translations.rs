use serde_json::{json, Map, Value};

pub const LANGS: &[(&str, &str)] = &[
    ("tr", "Türkçe"),
    ("en", "English"),
    ("de", "Deutsch"),
    ("fr", "Français"),
    ("es", "Español"),
    ("it", "Italiano"),
    ("pt", "Português"),
    ("ru", "Русский"),
    ("ar", "العربية"),
    ("zh", "中文"),
    ("ja", "日本語"),
    ("ko", "한국어"),
    ("nl", "Nederlands"),
    ("pl", "Polski"),
];

pub fn list() -> Value {
    let arr: Vec<Value> = LANGS
        .iter()
        .map(|(c, n)| json!({"code": c, "name": n}))
        .collect();
    Value::Array(arr)
}

type T = &'static [(&'static str, &'static str)];

pub fn get(lang: &str) -> Value {
    let table: T = match lang {
        "en" => EN,
        "de" => DE,
        "fr" => FR,
        "es" => ES,
        "it" => IT,
        "pt" => PT,
        "ru" => RU,
        "ar" => AR,
        "zh" => ZH,
        "ja" => JA,
        "ko" => KO,
        "nl" => NL,
        "pl" => PL,
        _ => TR,
    };
    let mut m = Map::new();
    for (k, v) in table {
        m.insert(k.to_string(), Value::String(v.to_string()));
    }
    m.insert("langs".into(), list());
    Value::Object(m)
}

